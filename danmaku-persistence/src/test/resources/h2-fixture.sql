-- TEST ONLY: H2 MySQL mode, not the production MySQL Flyway migration.
-- NUMERIC(20,0) models unsigned BIGINT values; collation/engine semantics differ.
CREATE TABLE danmaku_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id BINARY(16) NOT NULL UNIQUE,
  room_id VARCHAR(50) NOT NULL,
  user_id NUMERIC(20,0) NOT NULL CHECK (user_id >= 0 AND user_id <= 18446744073709551615),
  content VARCHAR(500) NOT NULL,
  send_time TIMESTAMP(3) NOT NULL
);
CREATE INDEX idx_room_time_id ON danmaku_messages(room_id, send_time, id);
CREATE INDEX idx_user_id ON danmaku_messages(user_id);
